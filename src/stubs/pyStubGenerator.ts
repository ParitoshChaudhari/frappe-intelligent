import * as fs from 'fs';
import * as path from 'path';
import { DocTypeSchema } from '../core/types';

/**
 * Generates PEP 561 compliant .pyi type stubs for Frappe DocTypes so Pyright/Pylance
 * can provide native IDE autocomplete and type verification.
 */
export class PyStubGenerator {
  public static mapFieldTypeToPython(fieldtype: string, options?: string): string {
    switch (fieldtype) {
      case 'Int':
      case 'Check':
        return 'int';
      case 'Float':
      case 'Currency':
      case 'Percent':
        return 'float';
      case 'Data':
      case 'Link':
      case 'Select':
      case 'Small Text':
      case 'Long Text':
      case 'Text':
      case 'Code':
      case 'Text Editor':
      case 'Date':
      case 'Datetime':
      case 'Time':
      case 'Dynamic Link':
        return 'str';
      case 'Table':
        if (options) {
          const childClass = options.replace(/[^a-zA-Z0-9]/g, '');
          return `list['${childClass}']`;
        }
        return 'list[Any]';
      default:
        return 'Any';
    }
  }

  public static generateDocTypeStub(schema: DocTypeSchema): string {
    const lines: string[] = [];
    lines.push('# Auto-generated by Frappe Intelligent. Do not edit manually.');
    lines.push('from typing import Any, Optional, Union, List');
    lines.push('from frappe.model.document import Document');
    lines.push('');
    lines.push(`class ${schema.name.replace(/[^a-zA-Z0-9]/g, '')}(Document):`);
    lines.push(`    """Frappe DocType: ${schema.name} (${schema.module || 'Core'})"""`);

    if (schema.fields.length === 0) {
      lines.push('    pass');
      return lines.join('\n');
    }

    for (const field of schema.fields) {
      const pyType = this.mapFieldTypeToPython(field.fieldtype, field.options);
      const customTag = field.is_custom ? '  # Custom Field' : '';
      lines.push(`    ${field.fieldname}: ${pyType}${customTag}`);
    }

    return lines.join('\n');
  }

  public static writeWorkspaceStubs(workspaceRoot: string, doctypes: DocTypeSchema[]): string {
    const targetDir = path.join(workspaceRoot, '.frappe', 'typings');
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    for (const schema of doctypes) {
      const stubContent = this.generateDocTypeStub(schema);
      const safeName = path.basename(schema.name).replace(/[^a-zA-Z0-9_-]/g, '_').toLowerCase();
      const fileName = `${safeName}.pyi`;
      fs.writeFileSync(path.join(targetDir, fileName), stubContent, 'utf8');
    }

    return targetDir;
  }
}
