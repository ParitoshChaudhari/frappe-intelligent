import * as fs from 'fs';
import * as path from 'path';
import { DocTypeSchema } from '../core/types';

/**
 * Generates ambient TypeScript declaration (.d.ts) files for VS Code's JavaScript
 * Language Server (TSServer) to power instant client-side autocomplete.
 */
export class JsStubGenerator {
  public static generateAmbientDeclarations(doctypes: DocTypeSchema[]): string {
    const lines: string[] = [];
    lines.push('// Auto-generated by Frappe Intelligent. Ambient Frappe Client Typings.');
    lines.push('declare namespace frappe {');
    lines.push('    function call(options: { method: string; args?: Record<string, any>; callback?: (r: { message: any }) => void; error?: (r: any) => void; freeze?: boolean; freeze_message?: string; async?: boolean }): Promise<any>;');
    lines.push('    function msgprint(msg: string | { message: string; title?: string; indicator?: string }): void;');
    lines.push('    function throw(msg: string, title?: string): void;');
    lines.push('    function show_alert(message: string | { message: string; indicator?: string }, seconds?: number): void;');
    lines.push('    function confirm(message: string, if_yes: () => void, if_no?: () => void): void;');
    lines.push('    function prompt(fields: any[], callback: (values: any) => void, title?: string, primary_action_label?: string): void;');
    lines.push('    function set_route(...args: string[]): void;');
    lines.push('    function get_route(): string[];');
    lines.push('    function format(value: any, df: object, options?: object, doc?: object): string;');
    lines.push('    let route_options: Record<string, any> | undefined;');
    lines.push('');
    lines.push('    namespace db {');
    lines.push('        function get_value(doctype: string, name: string | object, fieldname: string | string[]): Promise<any>;');
    lines.push('        function get_list(doctype: string, args?: { fields?: string[]; filters?: any; limit?: number }): Promise<any[]>;');
    lines.push('        function set_value(doctype: string, name: string, fieldname: string | object, value?: any): Promise<any>;');
    lines.push('        function count(doctype: string, args?: { filters?: any }): Promise<number>;');
    lines.push('        function exists(doctype: string, name: string | object): Promise<boolean>;');
    lines.push('    }');
    lines.push('');
    lines.push('    namespace datetime {');
    lines.push('        function nowdate(): string;');
    lines.push('        function now_datetime(): string;');
    lines.push('        function add_days(d: string | Date, days: number): string;');
    lines.push('        function add_months(d: string | Date, months: number): string;');
    lines.push('        function str_to_user(val: string): string;');
    lines.push('        function prettyDate(time: string | Date): string;');
    lines.push('    }');
    lines.push('');
    lines.push('    namespace model {');
    lines.push('        function set_value(doctype: string, docname: string, fieldname: string | object, value?: any): Promise<any>;');
    lines.push('        function get_doc(doctype: string, name: string): Record<string, any> | null;');
    lines.push('        function with_doctype(doctype: string, callback?: () => void): Promise<void>;');
    lines.push('    }');
    lines.push('');
    lines.push('    namespace realtime {');
    lines.push('        function on(event: string, callback: (data: any) => void): void;');
    lines.push('        function off(event: string, callback?: (data: any) => void): void;');
    lines.push('        function publish(event: string, message: any): void;');
    lines.push('    }');
    lines.push('');
    lines.push('    namespace ui {');
    lines.push('        class Dialog {');
    lines.push('            constructor(options: { title: string; fields: any[]; size?: string; primary_action_label?: string; primary_action?: (values: any) => void });');
    lines.push('            show(): void;');
    lines.push('            hide(): void;');
    lines.push('            get_values(as_dict?: boolean): Record<string, any> | null;');
    lines.push('            set_value(fieldname: string, value: any): void;');
    lines.push('            set_values(values: Record<string, any>): void;');
    lines.push('        }');
    lines.push('        namespace form {');
    lines.push('            function on(doctype: string, event_handlers: Record<string, (frm: any) => void>): void;');
    lines.push('        }');
    lines.push('    }');
    lines.push('}');
    lines.push('');
    lines.push('interface FrappeForm {');
    lines.push('    doc: Record<string, any>;');
    lines.push('    fields_dict: Record<string, any>;');
    lines.push('    set_value(fieldname: string, value: any): Promise<void>;');
    lines.push('    get_value(fieldname: string): any;');
    lines.push('    set_df_property(fieldname: string, property: string, value: any): void;');
    lines.push('    toggle_display(fieldname: string | string[], show: boolean): void;');
    lines.push('    toggle_enable(fieldname: string | string[], enable: boolean): void;');
    lines.push('    toggle_reqd(fieldname: string | string[], reqd: boolean): void;');
    lines.push('    refresh_field(fieldname: string): void;');
    lines.push('    add_custom_button(label: string, action: () => void, group?: string): any;');
    lines.push('    remove_custom_button(label: string, group?: string): void;');
    lines.push('    change_custom_button_type(label: string, group: string | null, type: string): void;');
    lines.push('    set_query(fieldname: string, opt: () => any): void;');
    lines.push('    set_intro(text: string, color?: string): void;');
    lines.push('    add_child(table_fieldname: string, values?: object): any;');
    lines.push('    clear_table(table_fieldname: string): void;');
    lines.push('    is_new(): boolean;');
    lines.push('    is_dirty(): boolean;');
    lines.push('    save(action?: string): Promise<void>;');
    lines.push('    reload_doc(): void;');
    lines.push('    scroll_to_field(fieldname: string): void;');
    lines.push('    disable_save(disable?: boolean): void;');
    lines.push('    enable_save(): void;');
    lines.push('    call(options: { method: string; args?: any; callback?: (r: any) => void }): Promise<any>;');
    lines.push('}');
    lines.push('');
    lines.push('declare const frm: FrappeForm;');
    lines.push('declare const cur_frm: FrappeForm;');
    lines.push('declare const locals: Record<string, Record<string, any>>;');
    lines.push('declare function __(str: string, replace?: any[]): string;');
    lines.push('');
    lines.push('// Generate Typed DocType Interfaces');
    for (const dt of doctypes) {
      const safeName = dt.name.replace(/[^a-zA-Z0-9]/g, '');
      lines.push(`interface ${safeName}Doc {`);
      for (const f of dt.fields) {
        const jsType = f.fieldtype === 'Int' || f.fieldtype === 'Check' ? 'number' : (f.fieldtype === 'Float' || f.fieldtype === 'Currency' || f.fieldtype === 'Percent' ? 'number' : 'string');
        lines.push(`    ${f.fieldname}?: ${jsType};`);
      }
      lines.push('}');
      lines.push('');
    }

    return lines.join('\n');
  }

  public static writeWorkspaceJsTypings(workspaceRoot: string, doctypes: DocTypeSchema[]): string {
    const targetDir = path.join(workspaceRoot, '.frappe', 'typings');
    if (!fs.existsSync(targetDir)) {
      fs.mkdirSync(targetDir, { recursive: true });
    }

    const content = this.generateAmbientDeclarations(doctypes);
    fs.writeFileSync(path.join(targetDir, 'frappe-ambient.d.ts'), content, 'utf8');

    return targetDir;
  }
}
